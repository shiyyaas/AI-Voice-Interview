import type { EvaluationPayload } from '@/lib/evaluation/evaluator';
import type { VoiceMessage } from '@/lib/voice/types';

export interface PortfolioExportData {
  sessionId: string;
  roleTitle: string;
  candidateType?: string;
  date: string;
  durationSeconds?: number;
  evaluation: EvaluationPayload;
  transcript: VoiceMessage[] | string;
}

export function generateSessionPortfolioMarkdown(data: PortfolioExportData): string {
  const durationText = data.durationSeconds
    ? `${Math.floor(data.durationSeconds / 60)}m ${data.durationSeconds % 60}s`
    : 'N/A';

  const strengthsList = data.evaluation.strengths.map((s) => `- ✅ ${s}`).join('\n');
  const weaknessesList = data.evaluation.weaknesses.map((w) => `- 🎯 ${w}`).join('\n');
  const exercisesList = data.evaluation.suggested_exercises.map((e, idx) => `${idx + 1}. 📝 ${e}`).join('\n');

  let transcriptBlock = '';
  if (Array.isArray(data.transcript)) {
    transcriptBlock = data.transcript
      .map((msg) => `> **${msg.role === 'assistant' ? 'Interviewer (AI)' : 'Candidate'}:**\n> ${msg.content}`)
      .join('\n\n');
  } else {
    transcriptBlock = data.transcript;
  }

  const comp = data.evaluation.competency_scores;

  return `# Technical Interview Session Portfolio
**Role Track:** ${data.roleTitle}
**Candidate Level / Type:** ${data.candidateType || 'Guest'}
**Date Evaluated:** ${data.date}
**Duration:** ${durationText}
**Session ID:** \`${data.sessionId}\`

---

## Performance Summary
- **Overall Readiness Score:** **${data.evaluation.overall_score} / 100**
- **Technical Accuracy:** ${data.evaluation.technical_score} / 100
- **Verbal Communication:** ${data.evaluation.communication_score} / 100
- **Confidence Rating:** ${data.evaluation.confidence_score} / 100

### Competency Radar Matrix
| Competency Dimension | Proficiency Score | Status |
| :--- | :--- | :--- |
| **Syntax Accuracy** | ${comp.syntaxAccuracy}% | ${comp.syntaxAccuracy >= 80 ? 'Mastered' : 'Developing'} |
| **System Architecture** | ${comp.systemArchitecture}% | ${comp.systemArchitecture >= 80 ? 'Mastered' : 'Developing'} |
| **Verbal Communication Fluency** | ${comp.verbalCommunication}% | ${comp.verbalCommunication >= 80 ? 'Mastered' : 'Developing'} |
| **Problem Solving** | ${comp.problemSolving}% | ${comp.problemSolving >= 80 ? 'Mastered' : 'Developing'} |
| **Code Quality** | ${comp.codeQuality}% | ${comp.codeQuality >= 80 ? 'Mastered' : 'Developing'} |

---

## Evaluator Critique & Key Takeaways
${data.evaluation.key_takeaways}

### Core Strengths
${strengthsList}

### Key Growth Opportunities
${weaknessesList}

### Targeted Practical Exercises
${exercisesList}

---

## Verbatim Interview Transcript
${transcriptBlock}

---
*Generated by VocalPrep AI Engine • Multi-tenant Row-Isolated Portfolio Export*
`;
}

export function downloadMarkdownFile(filename: string, content: string): void {
  if (typeof window === 'undefined') return;

  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
